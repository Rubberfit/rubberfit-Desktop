// engine/crates/rf-layout/tests/bench_summary.rs
//
// Task 17 companion tool: produces a markdown summary of pack()
// quality metrics (density, placed, overflow, wall-clock) across the
// 9 parity fixtures × 3 modes × 2 seeds.
//
// Runs as a regular test so it executes under `cargo test` BUT writes
// the full markdown table ONLY when REMA_WRITE_BENCH_REPORT=1 is set.
// Otherwise it exits with a trivial assertion so cargo-test time stays
// bounded by pack's time_budget_ms per sample.
//
// Invoke the report generation via:
//   REMA_WRITE_BENCH_REPORT=1 cargo test --test bench_summary --release -- --nocapture --test-threads=1
//
// Output lands at:
//   docs/superpowers/benchmarks/2026-04-18-s2.5-results.md

use rf_layout::application::pack::pack;
use rf_layout::domain::{PackMode, PackRequest, PackResult};
use std::fs;
use std::path::PathBuf;
use std::time::Instant;

const FIXTURES: &[&str] = &[
    "single-rect.json",
    "multi-rect-same-size.json",
    "rect-grid.json",
    "circle-grid.json",
    "trapezoid-mix.json",
    "mixed-rect-circle.json",
    "overflow.json",
    "multi-sheet-remnant.json",
    "cone-array.json",
];

struct RunSpec {
    mode: PackMode,
    mode_label: &'static str,
    budget_ms: u64,
}

const RUN_SPECS: &[RunSpec] = &[
    RunSpec {
        mode: PackMode::Fast,
        mode_label: "fast",
        budget_ms: 2_000,
    },
    RunSpec {
        mode: PackMode::Balanced,
        mode_label: "balanced",
        budget_ms: 10_000,
    },
    RunSpec {
        mode: PackMode::Thorough,
        mode_label: "thorough",
        budget_ms: 30_000,
    },
];
const SEEDS: &[u64] = &[42, 43];

struct Sample {
    fixture: String,
    mode: String,
    seed: u64,
    placed: u32,
    overflow: u32,
    density: f64,
    elapsed_ms: u128,
    was_cancelled: bool,
}

fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

fn load(name: &str) -> PackRequest {
    let path = fixture_dir().join(name);
    let content =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    serde_json::from_str(&content).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()))
}

fn run_sample(fixture: &str, spec: &RunSpec, seed: u64) -> Sample {
    let mut req = load(fixture);
    req.mode = Some(spec.mode);
    req.time_budget_ms = Some(spec.budget_ms);
    req.seed = Some(seed);

    let t0 = Instant::now();
    let result: PackResult = pack(req).expect("pack");
    let elapsed_ms = t0.elapsed().as_millis();

    Sample {
        fixture: fixture.to_string(),
        mode: spec.mode_label.to_string(),
        seed,
        placed: result.placed_count,
        overflow: result.overflow_count,
        density: result.overall_density,
        elapsed_ms,
        was_cancelled: result.was_cancelled,
    }
}

fn write_markdown(samples: &[Sample], out_path: &std::path::Path) {
    let mut out = String::new();
    out.push_str("# S2.5 Rust engine benchmark results\n\n");
    out.push_str(
        "Generated by `cargo test --test bench_summary --release` \
with `REMA_WRITE_BENCH_REPORT=1`. Measurements taken on the machine \
that ran the test; re-run locally for comparable numbers.\n\n",
    );
    out.push_str("Each row = one fixture × mode × seed sample. Modes map to budget ms:\n\n");
    out.push_str("- `fast` → 2000 ms\n");
    out.push_str("- `balanced` → 10000 ms\n");
    out.push_str("- `thorough` → 30000 ms\n\n");
    out.push_str("| Fixture | Mode | Seed | Placed | Overflow | Density | Elapsed (ms) |\n");
    out.push_str("|---------|------|------|-------:|---------:|--------:|-------------:|\n");
    for s in samples {
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {:.4} | {} |\n",
            s.fixture, s.mode, s.seed, s.placed, s.overflow, s.density, s.elapsed_ms
        ));
    }
    out.push_str("\n## Aggregates (seed=42 only)\n\n");
    out.push_str("| Fixture | Fast density | Balanced density | Thorough density |\n");
    out.push_str("|---------|------------:|----------------:|----------------:|\n");
    for fixture in FIXTURES {
        let f = samples
            .iter()
            .find(|s| s.fixture == *fixture && s.mode == "fast" && s.seed == 42);
        let b = samples
            .iter()
            .find(|s| s.fixture == *fixture && s.mode == "balanced" && s.seed == 42);
        let t = samples
            .iter()
            .find(|s| s.fixture == *fixture && s.mode == "thorough" && s.seed == 42);
        out.push_str(&format!(
            "| {} | {:.4} | {:.4} | {:.4} |\n",
            fixture,
            f.map(|s| s.density).unwrap_or(0.0),
            b.map(|s| s.density).unwrap_or(0.0),
            t.map(|s| s.density).unwrap_or(0.0),
        ));
    }
    out.push_str("\n## Cancellation\n\n");
    let cancelled_samples: Vec<_> = samples.iter().filter(|s| s.was_cancelled).collect();
    if cancelled_samples.is_empty() {
        out.push_str("No samples returned `wasCancelled = true` during this run.\n");
    } else {
        out.push_str(&format!(
            "{} samples terminated via cancel — re-examine the benchmark budget.\n",
            cancelled_samples.len()
        ));
    }

    if let Some(parent) = out_path.parent() {
        fs::create_dir_all(parent).expect("create bench dir");
    }
    fs::write(out_path, out).expect("write bench markdown");
}

#[test]
fn bench_summary_runs_each_fixture() {
    let write_report = std::env::var("REMA_WRITE_BENCH_REPORT").ok().as_deref() == Some("1");

    if !write_report {
        // Cheap smoke — just verify each fixture loads + packs under
        // Fast mode. Full sweep only runs when REMA_WRITE_BENCH_REPORT=1.
        for fixture in FIXTURES {
            let sample = run_sample(
                fixture,
                &RUN_SPECS[0], // Fast
                42,
            );
            assert!(
                sample.placed + sample.overflow > 0,
                "fixture {fixture} produced no items"
            );
        }
        return;
    }

    eprintln!("REMA_WRITE_BENCH_REPORT=1 set — running full sweep (this takes minutes)");
    let mut samples: Vec<Sample> = Vec::new();
    for fixture in FIXTURES {
        for spec in RUN_SPECS {
            for &seed in SEEDS {
                eprintln!("  {fixture} / {} / seed {seed}", spec.mode_label);
                samples.push(run_sample(fixture, spec, seed));
            }
        }
    }

    let out_path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(3) // .../engine/crates/rf-layout -> .../
        .expect("workspace root")
        .join("docs/superpowers/benchmarks/2026-04-18-s2.5-results.md");
    write_markdown(&samples, &out_path);
    eprintln!("wrote {}", out_path.display());
}
